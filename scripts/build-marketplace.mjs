// Builds the plugin marketplace from plugins/<id>/plugin.json and plugins/external.json:
//   plugins/marketplace.json  what the app reads, with a SHA-256 for every file (downloads that differ are refused)
//   plugins/MARKETPLACE.md    the same catalog as a page people can read on GitHub
// Run after changing a plugin:  npm run marketplace      CI:  npm run marketplace:check (fails when out of date)
import crypto from 'node:crypto'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { checkPlugin } from './plugin-check.mjs'
import { fetchExternal } from './external-plugins.mjs'

const ROOT = path.resolve('plugins')
const OUT = path.join(ROOT, 'marketplace.json')
const OUT_MD = path.join(ROOT, 'MARKETPLACE.md')
const REPO = 'https://github.com/mattgauzza/gauzzaDocs'
const sha = buf => crypto.createHash('sha256').update(buf).digest('hex')

const entry = (m, pathOrUrl, files, external) => ({
  id: m.id,
  name: m.name,
  version: m.version,
  description: m.description,
  author: m.author || '',
  category: m.category,
  tags: m.tags || [],
  icon: m.icon || '',
  languages: m.languages || [],
  minApi: m.minApi || 1,
  path: pathOrUrl,
  ...(external ? { external: true, homepage: m.homepage || pathOrUrl.replace(/^https:\/\/raw\.githubusercontent\.com\/([^/]+)\/([^/]+)\/.*/, 'https://github.com/$1/$2') } : {}),
  size: files.reduce((n, e) => n + e.size, 0),
  files
})

const plugins = []
for (const dir of fs.readdirSync(ROOT, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort()) {
  if (!fs.existsSync(path.join(ROOT, dir, 'plugin.json'))) continue
  const r = await checkPlugin(path.join(ROOT, dir))
  if (r.problems.length) {
    console.error(`plugins/${dir}:\n  - ${r.problems.join('\n  - ')}`)
    process.exit(1)
  }
  const m = r.manifest
  const files = [...new Set(['plugin.json', m.main, ...(m.files || [])])].map(f => {
    const buf = fs.readFileSync(path.join(ROOT, dir, f))
    return { path: f, sha256: sha(buf), size: buf.length }
  })
  plugins.push(entry(m, dir, files, false))
}
for (const ext of await fetchExternal(ROOT, os.tmpdir())) {
  if (ext.error) {
    console.error(`external ${ext.source}: ${ext.error}`)
    process.exit(1)
  }
  if (plugins.some(p => p.id === ext.manifest.id)) {
    console.error(`external plugin id "${ext.manifest.id}" is already taken`)
    process.exit(1)
  }
  plugins.push(entry(ext.manifest, ext.source, ext.files, true))
}
plugins.sort((a, b) => a.id.localeCompare(b.id))

const market = {
  name: 'gauzzaDocs plugin marketplace',
  schema: 1,
  repository: REPO,
  categories: [...new Set(plugins.map(p => p.category))].sort(),
  plugins
}
const json = JSON.stringify(market, null, 2) + '\n'

const cell = s => String(s || '').replace(/\|/g, '\\|')
const md = [
  '# gauzzaDocs plugin marketplace',
  '',
  '<!-- Generated by `npm run marketplace` from plugins/*/plugin.json and plugins/external.json. Do not edit by hand. -->',
  '',
  'Install these in the app under Plugins > Marketplace, or from a terminal with `gdocs plugins install <id>`. Every',
  'file is checked against the SHA-256 in [marketplace.json](marketplace.json) before it\'s installed.',
  '',
  `To add your own, see [submitting a plugin](README.md#submitting-a-plugin) or [fill in the submission form](${REPO}/issues/new?template=plugin-submission.yml).`,
  '',
  ...market.categories.flatMap(cat => [
    `## ${cat}`,
    '',
    '| | Plugin | Version | What it does | Works with |',
    '| --- | --- | --- | --- | --- |',
    ...plugins
      .filter(p => p.category === cat)
      .map(p => {
        const link = p.external ? p.homepage : `${p.path}/`
        const langs = !p.languages.length || p.languages.includes('*') ? 'any file' : p.languages.join(', ')
        return `| ${p.icon} | [**${cell(p.name)}**](${link}) \`${p.id}\`${p.external ? ' (community)' : ''} | ${p.version} | ${cell(p.description)} | ${cell(langs)} |`
      }),
    ''
  ])
].join('\n')

if (process.argv.includes('--check')) {
  const same = (f, text) => fs.existsSync(f) && fs.readFileSync(f, 'utf8') === text
  if (!same(OUT, json) || !same(OUT_MD, md)) {
    console.error('plugins/marketplace.json or MARKETPLACE.md is out of date: run npm run marketplace and commit the result')
    process.exit(1)
  }
  console.log(`marketplace is current (${plugins.length} plugins)`)
} else {
  fs.writeFileSync(OUT, json)
  fs.writeFileSync(OUT_MD, md)
  console.log(`wrote plugins/marketplace.json and MARKETPLACE.md: ${plugins.length} plugins in ${market.categories.length} categories`)
}
